export type EncMon = { id: string; lvl: [number, number]; w: number };

export function encountersFor(district: string): EncMon[] {
  const list: EncMon[] = [];
  const st = stageOf(district);
  const [w0, w1] = st.wild;
  const span = Math.max(1, w1 - w0);
  for (const id of DEX_ORDER) {
    const sp = DEX[id];
    if (sp.district !== district) continue;
    if (sp.legendary) continue;
    const w = sp.rarity === "rare" ? 2 : sp.rarity === "uncommon" ? 3 : 5;
    let lvl: [number, number];
    if (sp.rarity === "rare") lvl = [Math.round(w0 + span * 0.55), w1];
    else if (sp.rarity === "uncommon") lvl = [Math.round(w0 + span * 0.28), Math.round(w0 + span * 0.7)];
    else lvl = [w0, Math.round(w0 + span * 0.45)];
    list.push({ id, lvl, w });
  }
  return list.length ? list : [{ id: "mon_puffpuff", lvl: [2, 3], w: 1 }];
}

export function mixEnc(districts: string[], opts?: { legend?: boolean; map?: string; lv?: [number, number] }): EncMon[] {
  const out: EncMon[] = [];
  const band = opts?.map ? stageOf(opts.map).wild : opts?.lv;
  for (const d of districts) {
    for (const e of encountersFor(d)) {
      if (!opts?.legend && DEX[e.id]?.legendary) continue;
      out.push(band ? { ...e, lvl: band } : e);
    }
  }
  return out.length ? out : [{ id: "mon_puffpuff", lvl: [2, 3], w: 1 }];
}
