function assemble(): { dex: Record<string, Species>; order: string[] } {
  const dex: Record<string, Species> = { ...CORE_DEX };
  const extra = buildRoster();
  const legends: Species[] = [];
  const rest: Species[] = [];
  for (const sp of extra) {
    if (dex[sp.id]) continue;
    dex[sp.id] = sp;
    if (sp.legendary) legends.push(sp);
    else rest.push(sp);
  }
  const legendIds = legends.map((s) => s.id);
  const cap = 420 - legendIds.length;
  const order = [...CORE_ORDER, ...rest.map((s) => s.id)];
  if (order.length > cap) order.length = cap;
  const FILL = ["Bordstray", "Kiezwhelp", "Lampmite", "Gutterkin", "Neonwhelp", "Curbspawn", "Alleykin"];
  let n = 0;
  while (order.length < cap) {
    const name = FILL[n] ?? `Stray${n}`;
    n += 1;
    const id = `mon_${name.toLowerCase()}`;
    if (dex[id]) continue;
    dex[id] = {
      id,
      name,
      types: ["normal"],
      base: { hp: 44, atk: 48, def: 42, spa: 40, spd: 40, spe: 50 },
      moves: ["move_tackle", "move_scratch", "move_leer", "move_growl"],
      catch: 70,
      sprite: name.toLowerCase(),
      where: "Gasse A. Zu gewöhnlich für den Dex, zu hart für den Bordstein.",
      blurb: "Nachzügler. Lowtown zählt trotzdem.",
      rarity: "common",
      district: "alley",
    };
    order.push(id);
  }
  order.push(...legendIds);
  if (order.length > 420) order.length = 420;
  const keep = new Set(order);
  for (const id of Object.keys(dex)) {
    if (!keep.has(id)) delete dex[id];
  }
  return { dex, order };
}

